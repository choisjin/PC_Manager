const escapeRe = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

/** "{0}개 선택" → /^(.+?)개 선택$/ , "{0} selected" → "$1 selected" */
function compile([ko, en]: [string, string]): [RegExp, string] {
  const parts = ko.split(/\{(\d+)\}/)
  const order: number[] = []
  let source = '^'
  parts.forEach((part, i) => {
    if (i % 2 === 0) source += escapeRe(part)
    else {
      order.push(Number(part))
      source += '(.+?)'
    }
  })
  source += '$'
  const value = en.replace(/\$/g, '$$$$').replace(/\{(\d+)\}/g, (_, n: string) => `$${order.indexOf(Number(n)) + 1}`)
  return [new RegExp(source), value]
}

addExact(EXACT)
addPatterns(TEMPLATES.map(compile))
